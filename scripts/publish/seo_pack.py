def _kw_pos(text: str) -> int:
    i = text.find(KEYWORD)
    return i


def _cell(text: str) -> str:
    """يوتيوب يقبل | داخل العنوان، لكن جدول Markdown لا يقبلها بلا هروب."""
    return text.replace("|", "\\|")


def build_tags(extra: list[str], tail: list[str]) -> tuple[str, list[str]]:
    """أول وسم = الكلمة المفتاحية · بلا تكرار · تحت سقف 500 حرف.

    يبدأ بالقائمة الأساسية + الخاص بالحلقة، ثم يضيف الذيل (اللاتيني أولًا
    يُقلَّم) حتى يصل السقف. لا يُحذف أي وسم من الجزء العربي الخاص بالمحتوى.
    """
    tags: list[str] = []
    seen: set[str] = set()

    def push(t: str) -> None:
        t = t.strip()
        key = re.sub(r"[_\s]+", "", t).casefold()
        if t and key not in seen:
            seen.add(key)
            tags.append(t)

    for t in TAGS_CORE:
        push(t)
    for t in extra:
        push(t)
    for t in tail:
        candidate = ", ".join(tags + [t])
        if len(candidate) <= RULES["tags_max"]:
            push(t)
    line = ", ".join(tags)
    return line, tags


