def audit_episode(num: str, md: str) -> list[str]:
    errs: list[str] = []
    got = {m.group(1): m.group(2).strip() for m in
           re.finditer(r"\*\*العنوان ([AB]) — انسخ من هنا:\*\*\n+```text\n(.*?)```", md, re.S)}
    if set(got) != {"A", "B"}:
        return [f"[{num}] لم أجد بلوكَي عنوان A و B"]

    a, b = got["A"], got["B"]
    for tag, t in (("A", a), ("B", b)):
        if len(t) > RULES["title_max"]:
            errs.append(f"[{num}/{tag}] العنوان {len(t)} حرفًا > {RULES['title_max']}: {t}")
        if KEYWORD not in t:
            errs.append(f"[{num}/{tag}] الكلمة المفتاحية غائبة عن العنوان")
    if 0 <= _kw_pos(a) < RULES["title_a_hook"]:
        errs.append(f"[{num}/A] الكلمة المفتاحية في أول {RULES['title_a_hook']} حرفًا — يجب أن يأتي الهوك أولًا")
    if not (0 <= _kw_pos(b) < RULES["title_b_kw_by"]):
        errs.append(f"[{num}/B] الكلمة المفتاحية ليست داخل أول {RULES['title_b_kw_by']} حرفًا")

    m = re.search(r"## 2\. الوصف[^\n]*\n+```text\n(.*?)```", md, re.S)
    if not m:
        errs.append(f"[{num}] لا يوجد بلوك وصف")
        return errs
    desc = m.group(1)
    if KEYWORD not in desc[:RULES["desc_first"]]:
        errs.append(f"[{num}] الكلمة المفتاحية ليست في أول {RULES['desc_first']} حرفًا من الوصف")
    if desc.count(KEYWORD) < 3:
        errs.append(f"[{num}] الكلمة المفتاحية {desc.count(KEYWORD)} مرة فقط في الوصف (المطلوب ≥3)")
    if not (RULES["desc_min"] <= len(desc) <= RULES["desc_max"]):
        errs.append(f"[{num}] طول الوصف {len(desc)} خارج المدى")
    for must in (EPISODE_SOURCE, CHANNEL, "#", "الفصول"):
        if must not in desc:
            errs.append(f"[{num}] الوصف ينقصه: {must}")

    m = re.search(r"## 3\. الوسوم[^\n]*\n+```text\n(.*?)```", md, re.S)
    if not m:
        errs.append(f"[{num}] لا يوجد بلوك وسوم")
        return errs
    line = m.group(1).strip()
    tags = [t.strip() for t in line.split(",") if t.strip()]
    if len(line) > RULES["tags_max"]:
        errs.append(f"[{num}] الوسوم {len(line)} حرفًا > {RULES['tags_max']}")
    if len(tags) < RULES["tags_min"]:
        errs.append(f"[{num}] عدد الوسوم {len(tags)} < {RULES['tags_min']}")
    if tags[0] != KEYWORD:
        errs.append(f"[{num}] أول وسم «{tags[0]}» وليس «{KEYWORD}»")
    norm = [re.sub(r"[_\s]+", "", t).casefold() for t in tags]
    if len(norm) != len(set(norm)):
        dup = {t for t in norm if norm.count(t) > 1}
        errs.append(f"[{num}] وسوم مكرّرة: {dup}")
    return errs


def audit_short(key: str, md: str) -> list[str]:
    errs: list[str] = []
    m = re.search(r"## 2\. الوصف[^\n]*\n+```text\n(.*?)```", md, re.S)
    if not m:
        return [f"[{key}] لا يوجد بلوك وصف"]
    desc = m.group(1)
    if KEYWORD not in desc[:RULES["desc_first"]]:
        errs.append(f"[{key}] الكلمة المفتاحية ليست في أول {RULES['desc_first']} حرفًا من الوصف")
    m = re.search(r"## 3\. الوسوم[^\n]*\n+```text\n(.*?)```", md, re.S)
    if not m:
        return errs + [f"[{key}] لا يوجد بلوك وسوم"]
    line = m.group(1).strip()
    if len(line) > RULES["tags_max"]:
        errs.append(f"[{key}] الوسوم {len(line)} > {RULES['tags_max']}")
    tags = [t.strip() for t in line.split(",") if t.strip()]
    if tags[0] != KEYWORD:
        errs.append(f"[{key}] أول وسم «{tags[0]}» وليس «{KEYWORD}»")
    return errs


