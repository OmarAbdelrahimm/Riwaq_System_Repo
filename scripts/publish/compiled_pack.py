def main() -> int:
    from PIL import Image

    OUT.mkdir(parents=True, exist_ok=True)
    errs: list[str] = []

    for tag, spec in COVERS.items():
        im = EC.build(spec, "CMP", tag, corner="الحلقة المجمّعة")
        stem = naming.name("CMP", "CVR-H", "", variant=tag, v=1,
                           en=SLUG if tag == "A" else SLUG_B)
        jpg, _png = naming.save_cover(im, stem, OUT)
        S_ = str(jpg)
        errs += naming.check_name(jpg.name)
        Image.open(S_).verify()
        print(f"✅ {jpg.name}")

    md = render()
    errs += S.audit_episode("CMP", md)
    p = OUT / naming.seo_name("CMP", "", v=1, en=SLUG)
    p.write_text(md, encoding="utf-8")
    print(f"✅ {p.name}")

    if errs:
        print(f"\n❌ {len(errs)} مخالفة:")
        for e in errs:
            print("  ·", e)
        return 1
    print("✅ الحلقة المجمّعة: أغلفة + حزمة سيو مستوفاة القواعد")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
